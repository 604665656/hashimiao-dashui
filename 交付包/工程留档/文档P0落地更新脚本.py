s=open(p,encoding='utf-8').read().rstrip()+'''

---

# P0 三条链路增补（同四小节）

## 要解决什么

竞品调研给的三条 P0 一直没落地：提醒还是「无条件每 30 分钟弹」，完成目标后照催、凌晨也照催；饮水记录是可直接改的累加器，改了 `localStorage` 也看不出来；留存储仍隐含「断签清零」的压迫感。这轮把三条链路一起补完，**不加任何新功能入口、不新增生图与音频**。

## 怎么做的

**① 智能提醒**：`reminderDecision(now)` 是纯函数，按 7:00–22:00 三段累计曲线（早 30% / 中 50% / 晚 20%）算「此刻应喝多少」，与实际水量比对。落后 ≥250ml 且距上次提醒够久才弹；达标即停催；22:00–07:00 免打扰（1 分钟演示模式豁免，否则看不到效果）；连续忽略 2 次只升级一次「🫧 温柔提醒」，不轰炸。设置里可选「智能 / 固定间隔」，另有「🎯 专注 30 分钟」延期，每天最多 3 次。用户明确的「别吵我」（专注、免打扰、达标）**两种模式都生效**。喝水打卡会清掉忽略累计。HUD 有一行实时说明「为什么现在提醒 / 不提醒」。

**② 审计流水**：统一 `appendLog(day, rec, source)`，每笔补 `seq / prevHash / hash / localDate / auditSource`，哈希是同步 FNV 链（payload 含 `prevHash`，改任意一笔必断链），`file://` 下也能跑、不把打卡改成异步。来源区分 `quick / manual / selfie / avg-migrate / legacy`。老存档在 `init()` 最前面一次性补链，**只加元数据、不动 `id/ts/ml/type/note/photo`**。链头写进分享卡文案、卡面和 Toy 云档（`auditHead / auditOK`），接收方可按同版本规则复核。冲突时不冻结档案、不静默覆盖，只在 HUD 标红提示导出核对。

**③ 可信水合指数**：0–100，与积分 / 榜单 / Rank 完全解耦。公式 = 今日完成度 55% + 打卡节奏 20% + 近 7 天均值 25%，新用户给 **15 分信任基线**（不是一打开就 0）。漏记只按空白时长缓慢回落（每小时 −2，上限 −12，夜间不计），奶茶 −3 / 连打 −2，都**不清零**。里程碑 60 / 80 / 95 各送 1 张 🎫 修复券，用券后一小时内抵消空白衰减。HUD 显示指数条、历史最高、券数、审计链状态。

**接入面**：设置面板多两项（提醒策略、专注延期）；分享文案 / 卡面 / 结算台 / 剧场结算 / Toy 云档都带指数与链头；`renderAll()` 与 15 秒定时器同步刷新新指标。产物仍是单文件、零 CDN，61 张内嵌 WebP + 4 段 ogg 不变。

## 验证

无头浏览器 **14 组用例全过，0 发现项、0 控制台错误**。覆盖：审计链写入与链式衔接、篡改检出且不覆盖原记录、老存档迁移原字段（含照片 base64）不变、自首 / AVG 迁移都带链、智能提醒 9 种决策（落后 / 跟得上 / 达标 / 深夜 / 凌晨 / 固定 / 专注 / 柔性 / 间隔不足）、提醒真的写入且喝水清零、指数不清零与轻扣、里程碑发券与修复券、券状态落盘与老存档首次静默补齐、分享卡 / 云档接入、设置保存与延期上限、Toy 双形态冒烟、原有全链路（4 形象 / 防作弊 / 双榜 / 音效默认关 / 剧场 / 凌晨语录 / 刷新持久化）、375px 窄屏、体积与零外链。

产物 **845.2 KiB**，增量 **11.9 KiB**（纯逻辑，无新增素材），零外部资源引用。

## 坑

1. **审计来源字段名撞车**：初版用 `source`，但自首记录里 `source` 已经是「照片来源」（camera / placeholder），会被覆盖掉语义。改名 `auditSource`，原始 `source` 一字段不动。
2. **修复券自我发券循环**：用券把指数抬高 → `hiSync()` 又判定跨过下一个里程碑 → 再发一张券，净消耗 0。拆出 `hiRaw()`（自然值）只用于里程碑判定，`hydrationIndex()` 只负责展示（含修复抬升）。
3. **券状态没落盘**：`hiSync()` 改了 `hiTickets / hiBest / hiAwards` 却没 `save()`，刷新就重复发券。改成「只在状态真的变化时 save」，避免 15 秒定时器反复写。
4. **老存档首次打开刷屏**：高指数老用户第一次运行会同时跨过 60/80/95，弹 3 个 toast、补发 3 张历史券。加 `hiAwardsInit` 标记，首次静默补齐已达里程碑，之后的跨越才发券。
5. **固定间隔模式绕过「别吵我」**：初版把 `focusUntil` / 免打扰检查放在 `if(mode==='fixed')` 之后，用户选固定间隔再点专注仍会被催。把专注 / 免打扰 / 达标停催提到模式分支之前，演示模式单独豁免免打扰。
6. **测试断言把清晨词当 bug**：凌晨回归里「刚开机 / 天刚亮」只在 `isDeepNight()` 为真时才算违和，早上 8 点说这些其实合理。改成非深夜直接跳过该断言，去掉日志噪音。
7. **窄屏首屏被挤爆**：新增两行指标后，375px 下「今日打卡」卡片只剩标题、冷却与指数全要滚动才看得到。压缩 `.hi-box` 内边距 / 行高 / 进度条高度并把脚注改成单行省略，指标卡从 73px 压到 **58px**，回归仍 0 溢出。
8. **`AT()` 差点写进浏览器上下文**：回归里的时间构造函数定义在 Node 侧，`page.evaluate` 里调用会 ReferenceError。挪进 evaluate 函数体，另修了一处 `==>` 手滑。
'''
open(p,'w',encoding='utf-8').write(s)
